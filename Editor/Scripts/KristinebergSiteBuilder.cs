    const string OutDir = "Packages/com.smarc.assets/Runtime/Terrain/Kristineberg";
    const string PrefabDir = "Packages/com.smarc.assets/Runtime/Prefabs/Environment/GeoReferenced";
    const string AskoWorldPath = PrefabDir + "/AskoWorld.prefab";
    const string WorldPrefabPath = PrefabDir + "/KristinebergWorld.prefab";
    const string TerrainAssetPath = OutDir + "/KristinebergTerrain.asset";
    const string ScenePath = "Assets/Scenes/KristinebergEmpty.unity";
    const string MatDir = "Packages/com.smarc.assets/Runtime/Materials";
    const string MatTerrain = MatDir + "/DefaultHDTerrainLitMaterial.mat";  // same as Askö's terrain
    const string MatConcrete = MatDir + "/Concrete-ish.mat";
    const string MatDefault = MatDir + "/Default.mat";
    const string TileMaterialPath = MatDir + "/2DMapMaterial.mat";        // the one AskoWorld's tiler uses

