/// <summary>
/// Builds the Kristineberg site assets from the data produced by
/// data-cube/scripts/kristineberg-site/ :
///
///   KristinebergTerrain.asset   TerrainData from kristineberg_heightmap.r16
///   kristineberg_dock.asset     dock mesh (the quay face — vertical/overhanging,
///                               which a heightmap cannot represent)
///   kristineberg_buildings.asset
///   KristinebergWorld.prefab    cloned from AskoWorld.prefab so Ocean/Sky/Sun come
///                               from the proven Askö setup; only the terrain,
///                               structures and GLOBALREF differ
///   KristinebergEmpty.unity     the scene, modelled on AskoEmpty.unity
///
/// Frame: Unity +X = UTM 32N easting, +Z = UTM 32N northing, origin = K-berg origo
/// (58.249721 N, 11.44624 E). Water plane at y = 0. Provenance and the measurements
/// behind every number: _test_sites/Kristineberg/KRISTINEBERG_SITE.md
///
/// Vertices in the .smesh files are ALREADY in Unity scene coordinates — they are
/// assigned verbatim. No model importer is involved, so no axis convention can be
/// silently misapplied (the Beckholmen COLLADA lesson).
///
/// Run from menu: SMARC -> Build Kristineberg Site
/// Safe to re-run; overwrites the generated assets.
/// </summary>
public static class KristinebergSiteBuilder
{
